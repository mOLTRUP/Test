// Browser acceptance of the independent sales design proposal (synthetic data only).
const {chromium}=require('playwright');
const assert=require('node:assert/strict');
const path=require('node:path');
(async()=>{
 const browser=await chromium.launch({headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];
 page.on('pageerror',e=>errors.push(e.message));
 await page.goto('file://'+path.resolve(__dirname,'../design-udspil-2026-10-30/index.html'));
 await page.locator('[data-role-switch]').selectOption('seller');
 await page.locator('[data-page="countries"]').click();
 assert.match(await page.locator('[data-content]').innerText(),/Landepipeline/);
 assert.match(await page.locator('[data-content]').innerText(),/Danmark/);
 assert.equal(await page.locator('[data-content] [data-action="detail"]').count(),0,'Country totals must not expose individual seller leads');
 await page.locator('[data-page="pipeline"]').click();
 assert.equal(await page.locator('[data-drop-stage]').count(),6);
 await page.locator('[data-sort]').selectOption('prob');
 const lead=page.locator('[data-drag-id="3"]');
 await lead.dragTo(page.locator('[data-drop-stage="Dialog"]'));
 assert.equal(await page.locator('[data-drop-stage="Dialog"] [data-drag-id="3"]').count(),1);
 await page.locator('[data-drag-id="3"] [data-action="stage-note"]').click();
 await page.locator('[data-note-form] textarea').fill('Kontakt gennemført – næste skridt tilbud.');
 await page.locator('[data-note-form] button[type="submit"]').click();
 assert.match(await page.locator('[data-drag-id="3"]').innerText(),/Kontakt gennemført/);
 await page.locator('[data-drag-id="3"] [data-move-id]').selectOption('Resultat');
 assert.equal(await page.locator('[data-close-form]').count(),1);
 await page.locator('[data-close-form] button[type="submit"]').click();
 assert.equal(await page.locator('[data-close-form]').count(),1,'Cannot close without reason');
 await page.locator('[data-close-form] [name="outcome"]').selectOption('Pris');
 await page.locator('[data-close-form] button[type="submit"]').click();
 assert.equal(await page.locator('[data-drop-stage="Resultat"] [data-drag-id="3"]').count(),1);
 await page.locator('[data-action="new-lead"]').click();
 await page.locator('[data-lead-form] [name="name"]').fill('Testfirma med to produkter');
 await page.locator('[data-lead-form] [name="office"]').fill('Nyt kontor');
 await page.locator('[data-lead-form] [name="contact"]').fill('Anna');
 await page.locator('[data-lead-form] [name="phone"]').fill('+45 22 11 00 00');
 await page.locator('[data-lead-form] [name="product1"]').selectOption('Moms');
 await page.locator('[data-lead-form] [name="product2"]').selectOption('Færge');
 await page.locator('[data-lead-form] [name="files"]').setInputFiles({name:'aftale.txt',mimeType:'text/plain',buffer:Buffer.from('Kun fiktiv test')});
 await page.locator('[data-lead-form] [name="link"]').fill('https://example.com/aftale');
 await page.locator('[data-lead-form] button[type="submit"]').click();
 assert.equal(await page.locator('[data-lead-form]').count(),0);
 await page.locator('[data-page="leads"]').click();
 assert.match(await page.locator('[data-content]').innerText(),/Testfirma med to produkter/);
 const newLead=page.locator('[data-content] tr',{hasText:'Testfirma med to produkter'});
 await newLead.locator('[data-action="detail"]').click();
 assert.equal(await page.locator('[data-lead-form] [name="office"]').inputValue(),'Nyt kontor');
 assert.equal(await page.locator('[data-lead-form] [name="phone"]').inputValue(),'+45 22 11 00 00');
 assert.match(await page.locator('[data-lead-form]').innerText(),/aftale\.txt/);
 await page.locator('[data-action="close-modal"]').click();
 await page.locator('[data-page="activities"]').click();
 assert.match(await page.locator('[data-content]').innerText(),/Kommende opfølgninger/);
 await page.setViewportSize({width:390,height:844});
 await page.locator('[data-page="pipeline"]').click();
 assert.equal(await page.locator('[data-drop-stage]').count(),6);
 assert.ok(await page.locator('.pipeline-six').evaluate(n=>n.scrollWidth>n.clientWidth),'Mobile Kanban horizontally scrollable');
 assert.equal(errors.length,0,'No uncaught JS errors: '+errors.join(' | '));
 await browser.close();
 console.log('PASS: roles, aggregated country pipeline, six-stage Kanban, drag, notes, close reason, lead creation, files, links, mobile.');
})().catch(e=>{console.error(e);process.exit(1);});